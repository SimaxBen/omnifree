describe('encodeQr', () => {
  it('matches reference matrices bit for bit', () => {
    for (const f of FIXTURES) {
      const qr = encodeQr(f.text, f.ecc, f.mask);
      expect(qr.version).toBe(f.version);
      expect(qr.modules.map((r) => r.map((b) => (b ? '1' : '0')).join(''))).toEqual(f.rows);
    }
  });

  it('picks the smallest version and a valid mask automatically', () => {
    const qr = encodeQr('https://api.ilyasouhnine.tech/s/abc123');
    expect(qr.version).toBe(3);
    expect(qr.size).toBe(29);
    expect(qr.mask).toBeGreaterThanOrEqual(0);
    expect(qr.mask).toBeLessThan(8);
    // Finder pattern corners are dark.
    expect(qr.modules[0][0] && qr.modules[0][28] && qr.modules[28][0]).toBe(true);
  });

  it('grows the version with the payload and rejects oversize input', () => {
    expect(encodeQr('x'.repeat(300), 'M').version).toBeGreaterThan(9);
    expect(() => encodeQr('x'.repeat(4000), 'H')).toThrow(RangeError);
  });

  it('renders dark modules as one SVG path', () => {
    const qr = encodeQr('hi', 'L', 0);
    const dark = qr.modules.flat().filter(Boolean).length;
    expect(qrPath(qr).match(/M/g)).toHaveLength(dark);
    expect(qrPath(qr, 4)).toContain('M4 4h1v1h-1z');
  });
});
