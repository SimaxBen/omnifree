// Minimal QR Code encoder (byte mode, versions 1-40, ECC L/M/Q/H), after Nayuki's public-domain
// reference design. Enough to render short links and drop URLs as an inline SVG, without a dependency.

export type Ecc = 'L' | 'M' | 'Q' | 'H';

const ECC_INDEX: Record<Ecc, number> = { L: 0, M: 1, Q: 2, H: 3 };
const FORMAT_BITS: Record<Ecc, number> = { L: 1, M: 0, Q: 3, H: 2 };

